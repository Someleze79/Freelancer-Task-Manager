// ======================================================
// 🧭 MAIN APP ROUTING
// ======================================================

import {
  BrowserRouter,
  Routes,
  Route
} from "react-router-dom";

// ======================================================
// 🔥 REACT HOT TOAST
// ======================================================

import { Toaster } from "react-hot-toast";

// ======================================================
// 📄 PAGES
// ======================================================

import Login from "./pages/Login";
import Register from "./pages/Register";
import Dashboard from "./pages/Dashboard";

function App() {

  return (

    <BrowserRouter>

      {/* ======================================================
          🔥 GLOBAL TOAST NOTIFICATIONS
      ====================================================== */}

      <Toaster

        position="top-right"

        reverseOrder={false}

        toastOptions={{

          // ======================================================
          // 🎨 GLOBAL STYLING
          // ======================================================

          style: {

            background: "#0f172a",
            color: "#ffffff",
            border: "1px solid #334155",
            padding: "16px",
            borderRadius: "16px",
            fontSize: "14px"
          },

          // ======================================================
          // ✅ SUCCESS TOAST
          // ======================================================

          success: {

            duration: 3000
          },

          // ======================================================
          // ❌ ERROR TOAST
          // ======================================================

          error: {

            duration: 4000
          }
        }}
      />

        {/* ======================================================
            🛣️ ROUTES
        ====================================================== */}

        <Routes>

        {/* ======================================================
            🔐 LOGIN PAGE
        ====================================================== */}

        <Route
          path="/"
          element={<Login />}
        />

        {/* ======================================================
            📝 REGISTER PAGE
        ====================================================== */}

        <Route
          path="/register"
          element={<Register />}
        />

        {/* ======================================================
            🚀 DASHBOARD
        ====================================================== */}

        <Route
          path="/dashboard"
          element={<Dashboard />}
        />

      </Routes>

    </BrowserRouter>
  );
}

export default App;